-- The list checks (SQLite's triggers from 009, with the same messages).
CREATE FUNCTION lookup_values_no_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'list values are archived, never deleted';
END $$;
CREATE TRIGGER lookup_values_no_delete BEFORE DELETE ON lookup_values FOR EACH ROW EXECUTE FUNCTION lookup_values_no_delete();

CREATE FUNCTION lookup_values_id_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'a list value ID never changes; edit its label instead';
END $$;
CREATE TRIGGER lookup_values_id_fixed BEFORE UPDATE OF list, id ON lookup_values FOR EACH ROW EXECUTE FUNCTION lookup_values_id_fixed();

CREATE FUNCTION postings_lookups() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM lookup_values WHERE list = 'status' AND id = NEW.status) THEN
    RAISE EXCEPTION 'status is not in the status list';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM lookup_values WHERE list = 'stage' AND id = NEW.stage) THEN
    RAISE EXCEPTION 'stage is not in the stage list';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM lookup_values WHERE list = 'track' AND id = NEW.track) THEN
    RAISE EXCEPTION 'track is not in the track list';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER postings_lookups_insert BEFORE INSERT ON postings FOR EACH ROW EXECUTE FUNCTION postings_lookups();
CREATE TRIGGER postings_lookups_update BEFORE UPDATE OF status, stage, track ON postings FOR EACH ROW EXECUTE FUNCTION postings_lookups();

