-- PostgreSQL baseline (v3 Phase 4): the schema SQLite has after agent-core's 001-runs and this app's migrations
-- through 025-note-order, with the rows those migrations seed. It does not replay SQLite's history of table rebuilds.
-- db/postgres/migrate.ts runs it once and records every migration id it stands for; from 026 on, each SQLite migration
-- has a PostgreSQL file of the same name here. test/pg-schema.test.js holds the two schemas to the same tables, columns,
-- nullability, keys, and indexes.
--
-- Types: INTEGER PRIMARY KEY is an identity column (BY DEFAULT, so copied ids keep their values; the copy script resets
-- the sequences), REAL is double precision, BLOB is bytea. Timestamps stay ISO text and 0/1 flags stay integers, as the
-- code compares them that way. Token counts are bigint (the engine reads bigint back as a number).

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text UNIQUE,
  name text,
  role text NOT NULL CHECK (role IN ('admin', 'user')),
  status text NOT NULL CHECK (status IN ('active', 'pending', 'paused', 'rejected')),
  request_note text,
  terms_accepted_at text,
  decided_at text,
  decided_by integer,
  claude_key_enc text,
  ai_source text NOT NULL DEFAULT 'own' CHECK (ai_source IN ('own', 'owner')),
  ai_cap_usd double precision,
  created_at text NOT NULL,
  updated_at text NOT NULL,
  last_seen_at text,
  time_zone text
);

