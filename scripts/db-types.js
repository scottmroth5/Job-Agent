// Writes db/types.ts: one row type per table, read from the schema every migration builds (a fresh in-memory database,
// so no real data is opened). Run it after adding a migration; CI runs --check, which fails when db/types.ts is not what
// the migrations make.
//   npm run db:types              write db/types.ts
//   npm run db:types -- --check   exit 1 when db/types.ts is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { openJobStore } from '../db/index.ts';
import { repoPath } from '../tools/paths.ts';
/** @import { Database } from '../tools/types.ts' */

const OUT = repoPath('db', 'types.ts');
/** @type {Record<string, string | undefined>} */
const TS_TYPE = { INTEGER: 'number', REAL: 'number', TEXT: 'string', BLOB: 'Buffer' };

/** The table name as a type name: posting_notes -> PostingNotesRow. */
export const rowTypeName = (/** @type {string} */ table) => `${table.split('_').map((w) => w[0].toUpperCase() + w.slice(1)).join('')}Row`;

/**
 * db/types.ts for the schema of a migrated database.
 * @param {Database} db
 */
export function rowTypes(db) {
  const tables = /** @type {string[]} */ (db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").pluck().all());
  const out = [
    '// Row types for every table, as the migrations build them. Generated by npm run db:types from the schema; do not edit.',
    '// A column is nullable unless it is NOT NULL or the primary key. Queries that select other columns or expressions',
    '// declare their own result types.',
    '',
  ];
  for (const table of tables) {
    out.push(`export interface ${rowTypeName(table)} {`);
    const columns = /** @type {Array<{ name: string, type: string, notnull: number, pk: number }>} */ (db.prepare('SELECT name, type, "notnull", pk FROM pragma_table_info(?) ORDER BY cid').all(table));
    for (const c of columns) {
      const base = TS_TYPE[String(c.type).toUpperCase()] ?? 'unknown';
      out.push(`  ${c.name}: ${base}${c.notnull || c.pk ? '' : ' | null'};`);
    }
    out.push('}', '');
  }
  return out.join('\n');
}

function main() {
  const store = openJobStore(':memory:', { snapshot: false });
  let text;
  try {
    text = rowTypes(store.raw);
  } finally {
    store.close();
  }
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // missing counts as out of date
    }
    if (current !== text) {
      console.error('db/types.ts does not match the migrations. Run npm run db:types and commit the result.');
      process.exitCode = 1;
      return;
    }
    console.log('db/types.ts matches the migrations.');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`Wrote db/types.ts (${text.split('export interface').length - 1} tables).`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
